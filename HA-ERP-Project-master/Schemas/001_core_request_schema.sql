set define off
whenever sqlerror exit sql.sqlcode

create sequence supplier_request_number_seq start with 1000 increment by 1 nocache;

create table supplier_request (
  request_id number generated by default on null as identity (start with 1000) primary key,
  request_number varchar2(30) not null,
  requester_subject_id varchar2(200) not null,
  requester_display_name varchar2(200),
  requester_email varchar2(320),
  status varchar2(40) default 'DRAFT' not null,
  request_version number default 1 not null,
  supplier_name varchar2(240) not null,
  supplier_name_normalized varchar2(300),
  supplier_type varchar2(60) not null,
  country_code char(2) not null,
  address_line1 varchar2(240) not null,
  address_line2 varchar2(240),
  city varchar2(120) not null,
  state_or_province varchar2(120),
  postal_code varchar2(40),
  address_normalized varchar2(1000),
  contact_person varchar2(200),
  contact_email varchar2(320) not null,
  contact_phone varchar2(80),
  business_unit varchar2(120) not null,
  product_service_category varchar2(160),
  business_justification clob,
  expected_annual_spend number(18,2),
  currency_code char(3) default 'USD' not null,
  base_currency_code char(3) default 'USD' not null,
  base_currency_amount number(18,2),
  conversion_rate number(18,8),
  tax_registration_number varchar2(120),
  tax_registration_fingerprint varchar2(128),
  tax_registration_masked varchar2(120),
  bank_account_encrypted blob,
  bank_account_fingerprint varchar2(128),
  bank_account_last_four varchar2(4),
  bank_country_code char(2),
  bank_currency_code char(3),
  site_name varchar2(200),
  site_address_line1 varchar2(240),
  site_address_line2 varchar2(240),
  site_city varchar2(120),
  site_state_or_province varchar2(120),
  site_postal_code varchar2(40),
  site_country_code char(2),
  risk_score number(5,2) default 0 not null,
  risk_level varchar2(20) default 'LOW' not null,
  duplicate_level varchar2(20) default 'NONE' not null,
  fusion_supplier_id varchar2(80),
  fusion_supplier_number varchar2(80),
  fusion_create_error varchar2(1000),
  submitted_at timestamp with local time zone,
  reviewed_at timestamp with local time zone,
  created_at timestamp with local time zone default systimestamp not null,
  updated_at timestamp with local time zone default systimestamp not null,
  constraint supplier_request_number_uk unique (request_number),
  constraint supplier_request_status_chk check (
    status in (
      'DRAFT',
      'SUBMITTED',
      'VALIDATION_FAILED',
      'UNDER_REVIEW',
      'CORRECTION_REQUIRED',
      'REJECTED',
      'DUPLICATE',
      'APPROVED',
      'SUBMITTED_TO_FUSION',
      'CREATED_IN_FUSION',
      'INTEGRATION_FAILED'
    )
  ),
  constraint supplier_request_version_chk check (request_version > 0),
  constraint supplier_request_country_chk check (regexp_like(country_code, '^[A-Z]{2}$')),
  constraint supplier_request_site_country_chk check (site_country_code is null or regexp_like(site_country_code, '^[A-Z]{2}$')),
  constraint supplier_request_bank_country_chk check (bank_country_code is null or regexp_like(bank_country_code, '^[A-Z]{2}$')),
  constraint supplier_request_currency_chk check (regexp_like(currency_code, '^[A-Z]{3}$')),
  constraint supplier_request_base_curr_chk check (regexp_like(base_currency_code, '^[A-Z]{3}$')),
  constraint supplier_request_bank_curr_chk check (bank_currency_code is null or regexp_like(bank_currency_code, '^[A-Z]{3}$')),
  constraint supplier_request_email_chk check (regexp_like(contact_email, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$')),
  constraint supplier_request_spend_chk check (expected_annual_spend is null or expected_annual_spend >= 0),
  constraint supplier_request_base_spend_chk check (base_currency_amount is null or base_currency_amount >= 0),
  constraint supplier_request_rate_chk check (conversion_rate is null or conversion_rate > 0),
  constraint supplier_request_risk_score_chk check (risk_score >= 0 and risk_score <= 100),
  constraint supplier_request_risk_level_chk check (risk_level in ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
  constraint supplier_request_dup_level_chk check (duplicate_level in ('NONE', 'POSSIBLE', 'STRONG', 'EXACT'))
);

create table request_document (
  document_id number generated by default on null as identity (start with 1000) primary key,
  request_id number not null,
  request_version number not null,
  document_type varchar2(80) not null,
  file_name varchar2(255) not null,
  mime_type varchar2(120),
  document_content blob,
  is_latest char(1) default 'Y' not null,
  uploaded_by_subject_id varchar2(200) not null,
  uploaded_at timestamp with local time zone default systimestamp not null,
  constraint request_document_req_fk foreign key (request_id) references supplier_request (request_id),
  constraint request_document_latest_chk check (is_latest in ('Y', 'N')),
  constraint request_document_version_chk check (request_version > 0)
);
 