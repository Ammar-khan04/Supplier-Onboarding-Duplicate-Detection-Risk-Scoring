create table integration_job (
  job_id number generated by default on null as identity (start with 1000) primary key,
  parent_job_id number,
  request_id number,
  integration_type varchar2(40) not null,
  status varchar2(40) default 'READY' not null,
  attempt_number number default 1 not null,
  oic_instance_id varchar2(120),
  payload_reference varchar2(500),
  response_reference varchar2(500),
  error_type varchar2(120),
  error_message varchar2(1000),
  retryable char(1) default 'N' not null,
  correlation_id varchar2(120),
  created_at timestamp with local time zone default systimestamp not null,
  claimed_at timestamp with local time zone,
  started_at timestamp with local time zone,
  completed_at timestamp with local time zone,
  updated_at timestamp with local time zone default systimestamp not null,
  constraint integration_job_req_fk foreign key (request_id) references supplier_request (request_id),
  constraint integration_job_parent_fk foreign key (parent_job_id) references integration_job (job_id),
  constraint integration_job_type_chk check (integration_type in ('AI_EXPLANATION', 'FUSION_CREATE', 'SUPPLIER_SYNC')),
  constraint integration_job_status_chk check (status in ('READY', 'CLAIMED', 'IN_PROGRESS', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
  constraint integration_job_retryable_chk check (retryable in ('Y', 'N')),
  constraint integration_job_attempt_chk check (attempt_number > 0)
);
