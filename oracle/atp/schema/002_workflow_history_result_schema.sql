create table request_assessment (
  assessment_id number generated by default on null as identity (start with 1000) primary key,
  request_id number not null,
  request_version number not null,
  is_latest char(1) default 'Y' not null,
  validation_status varchar2(30) not null,
  validation_results_json clob not null,
  duplicate_level varchar2(20) default 'NONE' not null,
  duplicate_matches_json clob not null,
  risk_score number(5,2) default 0 not null,
  risk_level varchar2(20) default 'LOW' not null,
  deterministic_risk_score number(5,2) default 0 not null,
  reviewer_adjustment_points number(5,2) default 0 not null,
  reviewer_adjustment_reason varchar2(1000),
  reviewer_adjusted_by_subject_id varchar2(200),
  reviewer_adjusted_at timestamp with local time zone,
  risk_factors_json clob not null,
  reference_sync_id varchar2(120),
  assessed_by_subject_id varchar2(200),
  assessed_at timestamp with local time zone default systimestamp not null,
  constraint request_assessment_req_fk foreign key (request_id) references supplier_request (request_id),
  constraint request_assessment_latest_chk check (is_latest in ('Y', 'N')),
  constraint request_assessment_val_chk check (validation_status in ('PASSED', 'FAILED', 'WARNING')),
  constraint request_assessment_dup_chk check (duplicate_level in ('NONE', 'POSSIBLE', 'STRONG', 'EXACT')),
  constraint request_assessment_risk_chk check (risk_score >= 0 and risk_score <= 100),
  constraint req_assess_det_score_chk check (deterministic_risk_score >= 0 and deterministic_risk_score <= 100),
  constraint req_assess_adjust_pts_chk check (reviewer_adjustment_points in (0, 3, 5, 10)),
  constraint request_assessment_level_chk check (risk_level in ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
  constraint request_assessment_val_json_chk check (validation_results_json is json),
  constraint request_assessment_dup_json_chk check (duplicate_matches_json is json),
  constraint request_assessment_risk_json_chk check (risk_factors_json is json),
  constraint request_assessment_version_chk check (request_version > 0)
);

